function EventManagerA()

    print("EventManagerA : Entry")

    WaitPlayerEntry() -- 사람들이 들어올 때까지 기다림

    local Stage = nil
    Stage = 1

    local KQResult = nil
    KQResult = "Success"

    cBroadcast("all", "자, 이제부터 여러가지 적들이")
    cBroadcast("all", "여러분들의 앞을 막아설 것입니다.")
    cBroadcast("all", "모두들 행운을 빕니다.")

    -- Bloque [MainLoop]
    repeat
        while Stage <= 19 do
            cBroadcast("all", "다음 적이 나타날 때까지 잠시만 기다려 주십시오.")

            local RegenRoutine = nil
            RegenRoutine = "Regen_" .. Stage

            if _G[RegenRoutine] then _G[RegenRoutine]() end -- 적 리젠
            WaitMobRegen() -- 리젠될때까지 기다림
            WaitMobAnnihilation() -- 전멸할때까지 기다림

            Stage = Stage + 1
        end
    until true

    if KQResult == "Success" then
        cReward("KingdomQuest") -- 리워드를 줌
        cBroadcast("all", "모든 적을 물리치고 여행자던전을 통과하셨습니다.")
        cEndOfEvent("KingdomQuest", 1) -- 킹덤퀘스트 성공으로 마무리
    else
        cBroadcast("all", "여행자던전을 통과하지 못하셨습니다.")
        cEndOfEvent("KingdomQuest", 0) -- 킹덤퀘스트 실패로 마무리
    end

    cBroadcast("all", "30초후 루멘으로 이동합니다.")
    cWaitSec(10)
    cBroadcast("all", "20초후 루멘으로 이동합니다.")
    cWaitSec(10)
    cBroadcast("all", "10초후 루멘으로 이동합니다.")
    cWaitSec(5)
    cBroadcast("all", "5초후 루멘으로 이동합니다.")
    cWaitSec(5)
    cLinkTo("all", "Rou", "Rou", 7907, 8572)

    cMapClear("all")

end

