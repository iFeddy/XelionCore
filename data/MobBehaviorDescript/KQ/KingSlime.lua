function KQ_KingSlime()
    local SummonHPRate = nil
    local MaxHP = nil
    MaxHP = cCurrentHP()
    SummonHPRate = 1000

    cShout("all", "", "성스러운 슬라임들을 모욕하는 더러운 생명체들이여")
    cWaitSec(2)
    cShout("all", "", "너희들에게 영원한 저주를 내리노라!!!")

    while SummonHPRate > 0 do
        local CurHP = nil
        local CurHPRate = nil

        CurHP = cCurrentHP()
        CurHPRate = (CurHP * 1000) / MaxHP -- 주의 : 이런 수식은 뒤에서부터 실행됨!!!!

        print("MaxHP[" .. MaxHP .. "]  CurHP[" .. CurHP .. "]   CurHPRate[" .. CurHPRate .. "]   SummonHPRate[" .. SummonHPRate .. "]")

        if CurHPRate < SummonHPRate then
            cShout("all", "", "슬라임들이여, 내 힘을 받아 저들을 멸하여라!!")
            KingSlimeSummon()
            SummonHPRate = SummonHPRate - 200
        end
    end

    -- 킹슬라임이 죽었음
    local Mobs = nil
    Mobs = cHowManyMob("all")
    if Mobs < 15 then
        cShout("all", "", "아아, 정녕 슬라임의 시대는 갔단 말인가...")
    else
        cShout("all", "", "남아있는 슬라임들이여, 명예를 위해 최선을 다하라")
    end
end

